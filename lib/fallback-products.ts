function makeProduct(fp: FallbackProduct): AdminProduct {
  const catInfo = CATEGORY_MAP[fp.category] || {
    id: "cat-cord-sets",
    name: fp.category,
    slug: fp.category.toLowerCase().replace(/[^a-z0-9]+/g, "-"),
  };

  return {
    id: fp.id,
    name: fp.name,
    slug: fp.slug,
    description: fp.description,
    shortDescription: fp.name,
    status: "active",
    discountPrice: fp.discountPrice ? String(fp.discountPrice) : undefined,
    metaTitle: `${fp.name} | Mini Thailand BD`,
    metaDescription: fp.description.slice(0, 160),
    brandId: "b-minithai",
    categoryId: catInfo.id,
    brand: {
      id: "b-minithai",
      name: "Mini Thailand Exclusive",
      slug: "mini-thailand-exclusive",
      logoUrl: "/images/minithailand-logo.png",
    },
    category: {
      id: catInfo.id,
      name: catInfo.name,
      slug: catInfo.slug,
    },
    unit: {
      id: `u-${fp.id}`,
      name: "Piece",
      abbreviation: "PC",
      factor: 1,
      isActive: true,
    },
    media: fp.images.map((img, idx) => ({
      id: `med-${fp.id}-${idx}`,
      isFeatured: idx === 0,
      sortOrder: idx,
      mediaId: `med-id-${fp.id}-${idx}`,
      media: {
        id: `med-id-${fp.id}-${idx}`,
        url: img,
        type: "image",
      },
    })),
    variants: [
      {
        id: `var-${fp.id}-std`,
        sku: `MT-${fp.id.toUpperCase()}-001`,
        price: String(fp.price),
        cost: String(Math.round(fp.price * 0.65)),
        stockQuantity: 50,
        stockAlertThreshold: 5,
        isDefault: true,
        attributes: [
          { attributeValue: { attribute: { name: "Origin" }, value: "Thailand / Imported" } },
          { attributeValue: { attribute: { name: "Condition" }, value: "Brand New Boutique" } },
          { attributeValue: { attribute: { name: "Size" }, value: "Free Size (M to XL)" } },
        ],
      },
    ],
  } as unknown as AdminProduct;
}

